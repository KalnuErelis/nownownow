#!/usr/bin/env python3
"""Write src/data/affiliate-links.ts from an affiliate-sheet CSV export.

The CSV is the source of truth for the 160 live links (slug, tool, category,
url, sheet_row). Three more links are appended because they are already
published on /tools but were not separate rows in that export: mailforge,
infraforge, and artisan. URLs are copied exactly.
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "data" / "affiliate-links.ts"

EXTRAS = [
    {
        "slug": "mailforge",
        "tool": "mailforge.ai",
        "category": "Cold email infrastructure",
        "url": "https://mailforge.ai/?via=jaunius",
        "sheet_row": None,
    },
    {
        "slug": "infraforge",
        "tool": "infraforge.ai",
        "category": "Cold email infrastructure",
        "url": "https://infraforge.ai/?via=jaunius",
        "sheet_row": None,
    },
    {
        "slug": "artisan",
        "tool": "artisan.co",
        "category": "AI SDR",
        "url": "https://artisan.co/?ref=jaunius",
        "sheet_row": None,
    },
]


def sheet_row_literal(value: str | None) -> str:
    if value is None or value == "":
        return "null"
    if not value.isdigit():
        raise SystemExit(f"sheet_row is not an integer: {value!r}")
    return str(int(value))


def validate(row: dict[str, str | None], source: str) -> None:
    slug = row["slug"] or ""
    url = row["url"] or ""
    if not slug or not all(character.islower() or character.isdigit() or character == "-" for character in slug):
        raise SystemExit(f"{source}: invalid slug {slug!r}")
    if any(ord(character) < 32 or character.isspace() or character == "\\" for character in url):
        raise SystemExit(f"{source}: unsafe url for {slug}")
    if not (url.startswith("https://") or url.startswith("http://")):
        raise SystemExit(f"{source}: url must be http(s) for {slug}")


def emit(row: dict[str, str | None]) -> str:
    sheet_row = row.get("sheet_row")
    return "\n".join(
        [
            "  {",
            f"    slug: {json.dumps(row['slug'], ensure_ascii=False)},",
            f"    tool: {json.dumps(row['tool'], ensure_ascii=False)},",
            f"    category: {json.dumps(row['category'], ensure_ascii=False)},",
            f"    url: {json.dumps(row['url'], ensure_ascii=False)},",
            f"    sheetRow: {sheet_row_literal(sheet_row if isinstance(sheet_row, str) else None)},",
            "  }",
        ]
    )


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: python3 scripts/build_affiliate_links.py path/to/affiliate_links.csv")

    csv_path = Path(sys.argv[1])
    with csv_path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        fieldnames = reader.fieldnames or []
        expected = ["slug", "tool", "category", "url", "sheet_row"]
        if fieldnames != expected:
            raise SystemExit(f"unexpected columns: {fieldnames}")
        sheet_rows = list(reader)

    if len(sheet_rows) != 160:
        raise SystemExit(f"expected 160 sheet rows, found {len(sheet_rows)}")

    rows: list[dict[str, str | None]] = []
    for index, row in enumerate(sheet_rows, start=2):
        validate(row, f"csv line {index}")
        rows.append(row)
    for extra in EXTRAS:
        validate(extra, "extra")
        rows.append(extra)

    slugs = [row["slug"] for row in rows]
    urls = [row["url"] for row in rows]
    if len(set(slugs)) != len(slugs):
        raise SystemExit("duplicate slug")
    if len(set(urls)) != len(urls):
        raise SystemExit("duplicate url")

    body = ",\n".join(emit(row) for row in rows)
    contents = f"""/**
 * Affiliate redirect targets for /go/<slug>.
 *
 * Generated by scripts/build_affiliate_links.py. Do not hand-edit URLs.
 * 160 rows come from the affiliate sheet. mailforge, infraforge, and artisan
 * are published on /tools but were not separate rows in that export.
 * Query strings are copied exactly.
 */

export interface AffiliateLink {{
  slug: string;
  tool: string;
  category: string;
  url: string;
  /** Spreadsheet row. Null when the link was not a separate sheet row. */
  sheetRow: number | null;
}}

export const AFFILIATE_LINKS: readonly AffiliateLink[] = [
{body}
];

const bySlug = new Map<string, AffiliateLink>();
const byUrl = new Map<string, AffiliateLink>();

for (const link of AFFILIATE_LINKS) {{
  if (bySlug.has(link.slug) || byUrl.has(link.url)) {{
    throw new Error(`Duplicate affiliate link: ${{link.slug}}`);
  }}
  bySlug.set(link.slug, link);
  byUrl.set(link.url, link);
}}

export const AFFILIATE_LINKS_BY_SLUG: ReadonlyMap<string, AffiliateLink> = bySlug;

export function getAffiliateLink(slug: string): AffiliateLink | undefined {{
  return bySlug.get(slug);
}}

export function goPathForAffiliateUrl(url: string): string {{
  const link = byUrl.get(url);
  return link ? `/go/${{link.slug}}` : url;
}}
"""
    OUT.write_text(contents, encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} links)")


if __name__ == "__main__":
    main()
